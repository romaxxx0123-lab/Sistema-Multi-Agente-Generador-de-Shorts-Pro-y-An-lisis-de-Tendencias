FW, FH = 5, 7
# glyphs that need a narrower advance
NARROW = {'i': 3, 'l': 3, '.': 2, ',': 2, ':': 2, "'": 2, '!': 2, '·': 2,
          '(': 3, ')': 3, '[': 3, ']': 3, '¡': 2, 'j': 4, 't': 4, 'f': 4, '1': 4}


def font_sheet(max_w=480):
    """Pack glyphs into a multi-row sheet that fits inside the atlas.

    A single strip would be ~582px wide and get clipped by the 512px
    atlas, silently dropping the last glyphs (accents, N-tilde).
    """
    order = list(GLYPHS.keys())
    per_row = max(1, max_w // (FW + 1))
    rows_n = (len(order) + per_row - 1) // per_row
    img = Img(per_row * (FW + 1), rows_n * (FH + 1))
    meta = {}
    for i, ch in enumerate(order):
        gx = (i % per_row) * (FW + 1)
        gy = (i // per_row) * (FH + 1)
        for y, row in enumerate(GLYPHS[ch]):
            for x, c in enumerate(row):
                if c == '#':
                    img.set(gx + x, gy + y, C('#ffffff'))
        meta[ch] = [gx, gy, NARROW.get(ch, FW)]
    return img, meta


# ------------------------------------------------------------- UI panels
def wood_panel(w=48, h=48, seed=3):
    """9-slice source: carved wood plank with a metal-tack border."""
    rnd = random.Random(seed)
    img = Img(w, h)
    base = C('#5a4530')
    dark = C('#3d2d1e')
    lite = C('#75593c')
    edge = C('#2a1d13')
    trim = C('#8a6b45')
    # plank field with vertical grain
    for y in range(h):
        for x in range(w):
            img.set(x, y, base)
    for y in range(h):
        t = y / max(1, h - 1)
        if t < 0.30:
            img.hline(0, y, w, mix(base, lite, (0.30 - t) * 1.3))
        elif t > 0.70:
            img.hline(0, y, w, mix(base, dark, (t - 0.70) * 1.3))
    for _ in range(max(4, w // 8)):
        gx = rnd.randrange(2, max(3, w - 2)); gy = rnd.randrange(2, max(3, h - 5))
        for k in range(rnd.randrange(3, max(4, h // 2))):
            img.set(gx, gy + k, dark if rnd.random() < .6 else lite)
    for _ in range(w * h // 20):
        x, y = rnd.randrange(w), rnd.randrange(h)
        img.set(x, y, dark if rnd.random() < .55 else lite)
    # bevelled frame: 3px border
    img.rect(0, 0, w, 1, edge); img.rect(0, h - 1, w, 1, edge)
    img.rect(0, 0, 1, h, edge); img.rect(w - 1, 0, 1, h, edge)
    img.rect(1, 1, w - 2, 1, trim); img.rect(1, 1, 1, h - 2, trim)
    img.rect(1, h - 2, w - 2, 1, C('#33251a')); img.rect(w - 2, 1, 1, h - 2, C('#33251a'))
    img.rect(2, 2, w - 4, 1, C('#6b5238')); img.rect(2, 2, 1, h - 4, C('#6b5238'))
    return img


def parchment_panel(w=48, h=48, seed=9):
    """Lighter panel for tooltips / info boxes."""
    rnd = random.Random(seed)
    img = Img(w, h)
    base, dark, lite = C('#d9c79a'), C('#b5a179'), C('#efe2bd')
    for y in range(h):
        for x in range(w):
            img.set(x, y, base)
    for _ in range(w * h // 9):
        x, y = rnd.randrange(w), rnd.randrange(h)
        img.set(x, y, dark if rnd.random() < .5 else lite)
    img.rect(0, 0, w, 1, C('#6b5334')); img.rect(0, h - 1, w, 1, C('#6b5334'))
    img.rect(0, 0, 1, h, C('#6b5334')); img.rect(w - 1, 0, 1, h, C('#6b5334'))
    img.rect(1, 1, w - 2, 1, lite); img.rect(1, 1, 1, h - 2, lite)
    img.rect(1, h - 2, w - 2, 1, dark); img.rect(w - 2, 1, 1, h - 2, dark)
    return img


def button_panel(w=64, h=22, state='idle'):
    """Chunky wooden button with iron corner brackets."""
    if state == 'hover':
        base, lite, dark = C('#6d5439'), C('#8d6f4a'), C('#4a3826')
        trim = C('#d8b45c')
    elif state == 'press':
        base, lite, dark = C('#45341f'), C('#5d472e'), C('#2e2214')
        trim = C('#a8863f')
    else:
        base, lite, dark = C('#5a4530'), C('#75593c'), C('#3d2d1e')
        trim = C('#8a6b45')
    img = Img(w, h)
    img.rect(0, 0, w, h, base)
    # broad horizontal shading (top lit, bottom shaded) -> reads as a solid slab
    for y in range(h):
        t = y / max(1, h - 1)
        if t < 0.34:
            img.hline(0, y, w, mix(base, lite, (0.34 - t) * 1.5))
        elif t > 0.66:
            img.hline(0, y, w, mix(base, dark, (t - 0.66) * 1.5))
    # sparse long grain streaks, never full-height stripes
    rnd = random.Random(11)
    for _ in range(max(3, w // 9)):
        gx = rnd.randrange(2, max(3, w - 2))
        gy = rnd.randrange(2, max(3, h - 4))
        gl = rnd.randrange(2, max(3, h - gy - 1))
        col = dark if rnd.random() < .6 else lite
        for k in range(gl):
            img.set(gx, gy + k, col)
    for _ in range(w * h // 22):
        img.set(rnd.randrange(w), rnd.randrange(h), dark if rnd.random() < .5 else lite)
    # frame
    img.rect(0, 0, w, 1, C('#241a11')); img.rect(0, h - 1, w, 1, C('#241a11'))
    img.rect(0, 0, 1, h, C('#241a11')); img.rect(w - 1, 0, 1, h, C('#241a11'))
    img.rect(1, 1, w - 2, 1, trim)
    img.rect(1, 1, 1, h - 2, mix(trim, base, .4))
    img.rect(1, h - 2, w - 2, 1, C('#2e2214'))
    img.rect(w - 2, 1, 1, h - 2, C('#2e2214'))
    # iron corner brackets
    for (cx, cy, sx, sy) in [(1, 1, 1, 1), (w - 2, 1, -1, 1),
                             (1, h - 2, 1, -1), (w - 2, h - 2, -1, -1)]:
        for k in range(4):
            img.set(cx + sx * k, cy, C('#8f96a6'))
            img.set(cx, cy + sy * k, C('#8f96a6'))
        img.set(cx + sx, cy + sy, C('#c3c9d6'))
    return img


def slot_panel(sz=24, state='idle'):
    """Inventory slot: recessed dark well with a bevel."""
    img = Img(sz, sz)
    inner = C('#241c2a') if state == 'idle' else C('#2e2436')
    img.rect(0, 0, sz, sz, inner)
    for _ in range(sz * 2):
        r = random.Random(sz * 7 + _)
        img.set(r.randrange(sz), r.randrange(sz), C('#2b2233'))
    frame = C('#8a6b45') if state != 'hover' else C('#d8b45c')
    img.rect(0, 0, sz, 1, C('#1a1420')); img.rect(0, sz - 1, sz, 1, C('#1a1420'))
    img.rect(0, 0, 1, sz, C('#1a1420')); img.rect(sz - 1, 0, 1, sz, C('#1a1420'))
    img.rect(1, 1, sz - 2, 1, C('#3a2d1e')); img.rect(1, 1, 1, sz - 2, C('#3a2d1e'))
    img.rect(1, sz - 2, sz - 2, 1, frame); img.rect(sz - 2, 1, 1, sz - 2, frame)
    img.rect(2, 2, sz - 4, 1, C('#151019'))
    img.rect(2, 2, 1, sz - 4, C('#151019'))
    return img


