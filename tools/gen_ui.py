def logo_mark(size=1):
    """Emblem for the title: a compass rose over a leaf, in gold."""
    S = 40
    img = Img(S, S)
    G_D, G_M, G_L = C('#7a5a1c'), C('#c9a227'), C('#f4dd86')
    cx = cy = S / 2
    # outer ring
    for a in range(0, 360, 2):
        th = math.radians(a)
        img.set(int(cx + math.cos(th) * 17), int(cy + math.sin(th) * 17), G_M)
        img.set(int(cx + math.cos(th) * 16), int(cy + math.sin(th) * 16), G_D)
    for a in range(0, 360, 45):
        th = math.radians(a)
        img.set(int(cx + math.cos(th) * 18), int(cy + math.sin(th) * 18), G_L)
    # four-point star
    for i in range(4):
        th = i * math.pi / 2 - math.pi / 2
        for k in range(14):
            t = k / 14
            wdt = max(0, (1 - t) * 3.4)
            px = cx + math.cos(th) * k
            py = cy + math.sin(th) * k
            for o in range(-int(wdt), int(wdt) + 1):
                ox = -math.sin(th) * o
                oy = math.cos(th) * o
                col = G_L if (o < 0 or i == 3) else G_M
                img.set(int(px + ox), int(py + oy), col)
    # diagonal minor points
    for i in range(4):
        th = i * math.pi / 2 + math.pi / 4
        for k in range(8):
            t = k / 8
            wdt = max(0, (1 - t) * 1.8)
            px = cx + math.cos(th) * k
            py = cy + math.sin(th) * k
            for o in range(-int(wdt), int(wdt) + 1):
                img.set(int(px - math.sin(th) * o), int(py + math.cos(th) * o), G_D)
    # centre gem
    img.ellipse(cx, cy, 3.2, 3.2, C('#2f8fae'))
    img.ellipse(cx - .7, cy - .8, 1.7, 1.5, C('#8fdcf0'))
    img.set(int(cx) - 1, int(cy) - 1, C('#e0fbff'))
    img.outline_smart(tint=(28, 20, 14), strength=0.8)
    return img
