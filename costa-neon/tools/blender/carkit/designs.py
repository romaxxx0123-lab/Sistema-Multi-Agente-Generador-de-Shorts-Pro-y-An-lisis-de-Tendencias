# Diseños originales (sin marcas reales). Unidades: metros. Ejes de Blender: +Y adelante, +Z arriba,
# +X derecha; origen en el piso, en el centro de la distancia entre ejes.
# Las tablas son [[y, valor], ...] interpoladas con cúbica monótona.


def band(x0, x1, ylo, yhi, n=24):
    """Polígono en planta entre las curvas y = ylo(x) (atrás) e y = yhi(x) (adelante)."""
    xs = [x0 + (x1 - x0) * i / n for i in range(n + 1)]
    return [(x, ylo(x)) for x in xs] + [(x, yhi(x)) for x in reversed(xs)]


